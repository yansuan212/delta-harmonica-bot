def clean(src):
    """去掉歌词行 / 调号 / bpm 标记，只留纯简谱。
    歌词行里常带 _ 和 -，留在谱里会污染时值，必须删。"""
    keep = []
    for line in src.splitlines():
        s = line.strip()
        if not s or s.startswith("L:"):
            continue
        if s.startswith("/key"):
            continue
        if "bpm" in s.lower() or "ｂｐｍ" in s:
            continue
        keep.append(s)
    return "\n".join(keep)


def main(names=None):
    names = names or list(RAW)
    for name in names:
        if name not in RAW:
            print(f"[跳过] 未收录：{name}")
            continue
        item = RAW[name]
        jp = clean(item["src"])
        tonic = item.get("tonic", "C4")
        notes = H.parse_jianpu(jp, tonic)
        if not notes:
            print(f"[失败] 《{name}》没解析出音符")
            continue
        H.SONGS[name] = dict(bpm=item["bpm"], notes=notes, jianpu=jp, tonic=tonic)

        pitches = [H.note_to_midi(n) for n, _ in notes if n != "R"]
        lo, hi = H.midi_to_name(min(pitches)), H.midi_to_name(max(pitches))
        beats = sum(d for _, d in notes)
        secs = beats * 60.0 / item["bpm"]
        mods = {m for n, _ in notes if n != "R" for m in H.map_note(H.note_to_midi(n))[1]}
        keys = {H.map_note(H.note_to_midi(n))[0] for n, _ in notes if n != "R"}
        print(f"《{name}》 {len(notes)} 音符  音域 {lo}~{hi}  "
              f"{int(secs // 60)}:{int(secs % 60):02d}  用键 {''.join(sorted(keys))}  "
              f"修饰 {sorted(mods) or '无'}")

    H.save_songs()
    print(f"\n已写入 {H.SONGS_FILE}，当前共 {len(H.SONGS)} 首")


if __name__ == "__main__":
    main(sys.argv[1:])
