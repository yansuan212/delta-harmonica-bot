def main():
    H.SONGS.clear()
    H.SONGS.update(H.load_songs())
    before = len(H.SONGS)
    for name, item in SONGS_TO_ADD.items():
        notes = H.parse_jianpu(item["jianpu"], item["tonic"], item.get("octave_map"))
        if not notes:
            print(f"[失败] 《{name}》没解析出音符")
            continue
        H.SONGS[name] = dict(bpm=item["bpm"], notes=notes, jianpu=item["jianpu"],
                             tonic=item["tonic"], octave_map=item.get("octave_map"),
                             category=item.get("category", ""))
        pitches = [H.note_to_midi(n) for n, _ in notes if n != "R"]
        lo, hi = H.midi_to_name(min(pitches)), H.midi_to_name(max(pitches))
        beats = sum(d for _, d in notes)
        secs = beats * 60.0 / item["bpm"]
        print(f"《{name}》 {len(notes)} 音符  音域 {lo}~{hi}  "
              f"{int(secs // 60)}:{int(secs % 60):02d}  [{item.get('category', '')}]")
    H.save_songs()
    print(f"\n{len(SONGS_TO_ADD)} 首：{before} -> {len(H.SONGS)} 首")


if __name__ == "__main__":
    main()
