def main(names=None):
    H.SONGS.clear()
    H.SONGS.update(H.load_songs())
    for name in (names or list(SONGS_TO_ADD)):
        if name not in SONGS_TO_ADD:
            print(f"[跳过] 未收录：{name}")
            continue
        item = SONGS_TO_ADD[name]
        tonic = item["tonic"]
        notes = H.parse_jianpu(item["jianpu"], tonic, item.get("octave_map"))
        if not notes:
            print(f"[失败] 《{name}》没解析出音符")
            continue
        H.SONGS[name] = dict(bpm=item["bpm"], notes=notes, jianpu=item["jianpu"],
                             tonic=tonic, octave_map=item.get("octave_map"))

        pitches = [H.note_to_midi(n) for n, _ in notes if n != "R"]
        lo, hi = H.midi_to_name(min(pitches)), H.midi_to_name(max(pitches))
        beats = sum(d for _, d in notes)
        secs = beats * 60.0 / item["bpm"]
        mods = {m for n, _ in notes if n != "R" for m in H.map_note(H.note_to_midi(n))[1]}
        keys = {H.map_note(H.note_to_midi(n))[0] for n, _ in notes if n != "R"}
        print(f"《{name}》 {len(notes)} 音符  音域 {lo}~{hi}  "
              f"{int(secs // 60)}:{int(secs % 60):02d}  用键 {''.join(sorted(keys))}  "
              f"修饰 {sorted(mods) or '无'}")

    H.save_songs()
    print(f"\n已写入 songs.json，当前共 {len(H.SONGS)} 首")


if __name__ == "__main__":
    main(sys.argv[1:])
